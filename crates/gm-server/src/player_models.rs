/// `player_manager.TranslatePlayerModel`: the model path of a name, kleiner for an unknown one.
pub fn translate(name: &str) -> &'static str {
    PLAYER_MODELS
        .iter()
        .find(|e| e.0.eq_ignore_ascii_case(name))
        .map_or("models/player/kleiner.mdl", |e| e.1)
}

/// `player_manager.TranslatePlayerHands`: the hands of a name; an unknown name gets the
/// citizen hands with the fallback bodygroups the game reports.
pub fn hands(name: &str) -> Hands {
    PLAYER_MODELS
        .iter()
        .find(|e| e.0.eq_ignore_ascii_case(name))
        .map_or(
            Hands {
                model: "models/weapons/c_arms_citizen.mdl",
                skin: 0,
                body: "100000000",
            },
            |e| Hands {
                model: e.2,
                skin: e.3,
                body: e.4,
            },
        )
}

/// Index of a model path in the table for the wire (255 when it is not in it).
pub fn index_of(path: &str) -> u8 {
    PLAYER_MODELS
        .iter()
        .position(|e| e.1.eq_ignore_ascii_case(path))
        .map_or(255, |i| i as u8)
}

/// The model path of a wire index; anything outside the table draws as kleiner.
pub fn path_of_index(i: u8) -> &'static str {
    PLAYER_MODELS
        .get(i as usize)
        .map_or("models/player/kleiner.mdl", |e| e.1)
}

/// The name of a model path (`player_manager.TranslateToPlayerModelName`), if it is in the table.
pub fn name_of(path: &str) -> Option<&'static str> {
    PLAYER_MODELS
        .iter()
        .find(|e| e.1.eq_ignore_ascii_case(path))
        .map(|e| e.0)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn table_matches_the_recording() {
        assert_eq!(PLAYER_MODELS.len(), 87);
        assert_eq!(translate("kleiner"), "models/player/kleiner.mdl");
        assert_eq!(translate("nonsense"), "models/player/kleiner.mdl");
        assert_eq!(translate("combine"), "models/player/combine_soldier.mdl");
        assert_eq!(hands("police").model, "models/weapons/c_arms_combine.mdl");
        assert_eq!(hands("male01").skin, 1);
        assert_eq!(
            name_of("models/player/Group01/female_01.mdl"),
            Some("female01")
        );
    }
}
