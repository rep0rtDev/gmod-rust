#!/usr/bin/env python3
"""Regenerate crates/gm-script/src/glua/enums.luau from the wiki page cache
(.local/glua/pages/Enums__*.json): every documented constant as `K = K or value`
under a `-- @enum NAME` marker that `glua_list` counts."""
import json, glob, re, sys
cache = sys.argv[1] if len(sys.argv) > 1 else '.local/glua/pages'
items_re = re.compile(r'<item\s+key="([^"]+)"\s+value="([^"]*)"', re.S)
out = ['-- GLua enumerations: the documented constant tables (names and values as the game',
       '-- publishes them). A constant another runtime file already defines keeps its value.',
       '-- Generated by tools/glua/gen_enums.py from the wiki page cache.', '']
for f in sorted(glob.glob(cache + '/Enums__*.json')):
    p = json.load(open(f))
    addr, mk = p.get('address', ''), p.get('markup', '')
    items = items_re.findall(mk)
    if not addr.startswith('Enums/') or not items:
        continue
    out.append('-- @enum ' + addr.split('/', 1)[1])
    for k, v in items:
        if not re.match(r'^[A-Za-z_][A-Za-z0-9_]*$', k):
            continue
        v = v.strip()
        lit = v if re.match(r'^-?\d+(\.\d+)?$|^-?\d+e\d+$', v, re.I) else '"' + v.replace('\\', '\\\\').replace('"', '\\"') + '"'
        out.append(f'{k} = {k} or {lit}')
open('crates/gm-script/src/glua/enums.luau', 'w').write('\n'.join(out) + '\n')
